// Regenerates src/golden/goldenData.ts from assets/golden/.
//
// The golden photos are embedded as base64 instead of being bundled as image assets: in a standalone
// Android build an image asset resolves to a bare drawable name, not a file path, so it cannot be read
// back as bytes. Run after changing the golden files:  node scripts/embed-golden.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const b64 = (name) => readFileSync(join(root, 'assets/golden', name)).toString('base64');

const out = `// GENERATED by scripts/embed-golden.mjs from assets/golden/. Do not edit by hand.
export const GOLDEN_224_PNG_BASE64 =
  '${b64('example_224.png')}';

export const GOLDEN_256_JPG_BASE64 =
  '${b64('example_256.jpg')}';
`;
writeFileSync(join(root, 'src/golden/goldenData.ts'), out);
console.log('wrote src/golden/goldenData.ts', out.length, 'bytes');
