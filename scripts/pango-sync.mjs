#!/usr/bin/env node
// Converts the design canvas art (design/pango/pango.svg) into data the app renders (src/pango/art.generated.ts).
// Run after changing the art on the canvas: copy its <svg> into design/pango/pango.svg, then `npm run pango:sync`.
//
// The source is the canvas component's markup, holes included:
//   display="{{d.x}}"      -> node.show = 'x' (drawn only when that part is on)
//   class="pg-tail" etc.   -> node.anim = 'tail' (the part moves; see src/pango/motion.ts)
//   fill="{{scarf.main}}"  -> '$scarf.main' (filled in at render time)
//   id / href / url(#..)   -> short ids without the per-instance suffix (each native Svg has its own ids)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(join(root, 'design/pango/pango.svg'), 'utf8');

const ANIMS = new Set([
  'breathe', 'lift', 'blink', 'tail', 'scarf-tails', 'head-pose', 'wave', 'dart', 'beam', 'scanline', 'food',
  'chomp', 'tongue', 'figure', 'shadow', 'spark', 'dot', 'sweat', 'ball-breathe', 'z', 'ball-spin',
]);
// Parts whose CSS uses transform-box: fill-box, so they turn about their own centre.
const OWN_CENTRE = new Set(['spark', 'dot', 'z']);

const camel = (name) => name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const shortId = (id) => id.replace(/^pg-/, '').replace(/-\{\{uid\}\}$/, '');

function convertValue(name, value) {
  if (name === 'href') return '#' + shortId(value.slice(1));
  if (value.includes('url(#pg-{{patternId}}-{{uid}})')) return '$pattern';
  const urlFixed = value.replace(/url\(#(pg-[a-z]+-\{\{uid\}\})\)/g, (_, id) => `url(#${shortId(id)})`);
  const hole = urlFixed.match(/^\{\{\s*([\w.]+)\s*\}\}$/);
  if (hole) return '$' + hole[1];
  if (urlFixed.includes('{{')) throw new Error(`Unsupported partial hole in ${name}="${value}"`);
  return urlFixed;
}

function parse(markup) {
  const top = { t: '#root', a: {}, c: [] };
  const stack = [top];
  const tagRe = /<(\/?)([a-zA-Z]+)((?:\s+[a-zA-Z:-]+="[^"]*")*)\s*(\/?)>/g;
  let m;
  while ((m = tagRe.exec(markup))) {
    const [, closing, tag, rawAttrs, selfClosing] = m;
    if (closing) {
      const open = stack.pop();
      if (open.t !== tag) throw new Error(`Mismatched </${tag}> (open: <${open.t}>)`);
      continue;
    }
    const node = { t: tag, a: {} };
    // The root <svg>'s attributes are the canvas's sizing and labelling; the app does its own.
    const attrs = tag === 'svg' ? [] : rawAttrs.matchAll(/([a-zA-Z:-]+)="([^"]*)"/g);
    for (const [, name, value] of attrs) {
      if (name === 'class') {
        for (const cls of value.split(/\s+/)) {
          const key = cls.replace(/^pg-/, '');
          if (ANIMS.has(key)) node.anim = key;
          const delayed = key.match(/^(spark|dot|z)-(\d)$/);
          if (delayed) node.delay = Number(delayed[2]) - 1;
        }
        continue;
      }
      if (name === 'display') {
        const hole = value.match(/^\{\{\s*d\.(\w+)\s*\}\}$/);
        if (!hole) throw new Error(`Unexpected display="${value}"`);
        node.show = hole[1];
        continue;
      }
      if (name === 'id') {
        node.a.id = shortId(value);
        continue;
      }
      node.a[camel(name)] = convertValue(name, value);
    }
    stack[stack.length - 1].c ??= [];
    stack[stack.length - 1].c.push(node);
    if (!selfClosing) stack.push(node);
  }
  if (stack.length !== 1) throw new Error('Unclosed tags in source');
  return top.c[0];
}

// Centre of a part's own drawing, for parts that turn about themselves.
function bbox(node, box = { x0: Infinity, y0: Infinity, x1: -Infinity, y1: -Infinity }) {
  const add = (x, y) => {
    box.x0 = Math.min(box.x0, x); box.y0 = Math.min(box.y0, y);
    box.x1 = Math.max(box.x1, x); box.y1 = Math.max(box.y1, y);
  };
  if (node.t === 'circle') {
    const [cx, cy, r] = ['cx', 'cy', 'r'].map((k) => Number(node.a[k]));
    add(cx - r, cy - r); add(cx + r, cy + r);
  } else if (node.t === 'path') {
    if (/[a-z]/.test(node.a.d.replace(/[eE]/g, ''))) throw new Error('Relative path in a self-centred part');
    const nums = node.a.d.match(/-?\d*\.?\d+/g).map(Number);
    for (let i = 0; i + 1 < nums.length; i += 2) add(nums[i], nums[i + 1]);
  }
  for (const child of node.c ?? []) bbox(child, box);
  return box;
}

function annotate(node) {
  if (node.anim && OWN_CENTRE.has(node.anim)) {
    const b = bbox(node);
    node.o = [Number(((b.x0 + b.x1) / 2).toFixed(2)), Number(((b.y0 + b.y1) / 2).toFixed(2))];
  }
  for (const child of node.c ?? []) annotate(child);
  return node;
}

const svg = annotate(parse(source));
const defs = svg.c.find((n) => n.t === 'defs');
const scene = svg.c.filter((n) => n.t !== 'defs');
const out = `// Generated by scripts/pango-sync.mjs from design/pango/pango.svg. Do not edit by hand: change the art on the
// design canvas, copy it into design/pango/pango.svg and run \`npm run pango:sync\`.
import type { ArtNode } from './types';

export const DEFS: ArtNode[] = ${JSON.stringify(defs.c)};

export const SCENE: ArtNode[] = ${JSON.stringify(scene)};
`;
writeFileSync(join(root, 'src/pango/art.generated.ts'), out);
console.log(`pango-sync: ${defs.c.length} defs, ${scene.length} top-level parts written to src/pango/art.generated.ts`);
